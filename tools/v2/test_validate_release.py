#!/usr/bin/env python3
"""Independent corruption controls for the versioned release validator."""
import gzip
import hashlib
import importlib.util
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('release_checks', ROOT / 'tools/v2/validate_release.py')
checks = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checks)


class ReleaseControls(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='v2-release-control-')
        self.root = pathlib.Path(self.tmp.name)
        for p in checks.payload(ROOT):
            dest = self.root / p.relative_to(ROOT)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, dest)
        # Register the disposable snapshot independently. The immutable v1
        # evidence lock must still reject corruption even after rehashing v2.
        self.inventory = 'release/manifest-v2.json'
        manifest = json.loads((self.root / checks.MANIFEST).read_text())
        manifest['self_excluded'] = [self.inventory]
        manifest['files'] = [dict(path=str(p.relative_to(self.root)),
                                  sha256=hashlib.sha256(p.read_bytes()).hexdigest(),
                                  bytes=p.stat().st_size,
                                  mode='100755' if p.stat().st_mode & 0o111 else '100644')
                             for p in checks.payload(self.root)
                             if str(p.relative_to(self.root)) != self.inventory]
        (self.root / self.inventory).write_text(json.dumps(manifest, indent=2) + '\n')

    def tearDown(self):
        self.tmp.cleanup()

    def rejected(self, key):
        result = checks.validate(self.root, inventory=self.inventory)
        self.assertEqual(result['status'], 'FAIL', result)
        self.assertTrue(any(key in x for x in result['errors']), result['errors'])
        return result

    def test_positive_and_historical_navigation(self):
        result = checks.validate(self.root, inventory=self.inventory)
        self.assertEqual(result['status'], 'PASS', result['errors'])
        self.assertEqual(result['archived_references_resolved_by_explicit_ledger'], 24)
        self.assertEqual(result['accepted_evidence_entries'], 77)
        self.assertEqual(result['figures_checked'], 8)
        self.assertEqual(result['reviewed_waveform_traces_checked'], 1)

    def test_authentic_compressed_trace(self):
        p = self.root / checks.WAVEFORM_TRACE
        self.assertEqual(p.stat().st_size, checks.WAVEFORM_GZIP_BYTES)
        self.assertEqual(hashlib.sha256(p.read_bytes()).hexdigest(), checks.WAVEFORM_GZIP_SHA256)
        text = checks.reviewed_waveform_text(self.root)
        self.assertTrue(text.startswith('$version Generated by VerilatedVcd $end\n'))
        self.assertEqual(hashlib.sha256(text.encode()).hexdigest(), checks.WAVEFORM_VCD_SHA256)
        result = checks.validate(self.root)
        self.assertEqual(result['status'], 'PASS', result['errors'])

    def test_unregistered_gzip_rejected(self):
        (self.root / 'unreviewed.vcd.gz').write_bytes(gzip.compress(b'unreviewed trace'))
        self.rejected('payload_file_set')
        self.rejected('unexpected_binary')

    def test_inventory_cannot_authorize_other_binary_paths(self):
        manifest = self.root / self.inventory
        original = manifest.read_bytes()
        cases = [('other.vcd.gz', gzip.compress(b'unreviewed trace')),
                 ('other.txt.gz', b'ASCII content is not an authorized gzip.\n'),
                 ('other.zip', gzip.compress(b'unreviewed archive')),
                 ('other.vcd', gzip.compress(b'unreviewed simulator dump'))]
        for name, data in cases:
            with self.subTest(path=name):
                p = self.root / name
                p.write_bytes(data)
                value = json.loads(original)
                value['files'].append(dict(path=name, sha256=hashlib.sha256(data).hexdigest(),
                                           bytes=len(data), mode='100644'))
                manifest.write_text(json.dumps(value))
                result = self.rejected('unexpected_binary')
                self.assertTrue(any(x.get('unexpected_binary') == name for x in result['errors']))
                self.assertFalse(any('payload_hash' in x or 'payload_file_set' in x
                                     for x in result['errors']), result['errors'])
                p.unlink()
        manifest.write_bytes(original)

    def test_modified_registered_trace_rejected(self):
        p = self.root / checks.WAVEFORM_TRACE
        data = bytearray(p.read_bytes())
        data[-1] ^= 1
        p.write_bytes(data)
        self.rejected('payload_hash')
        self.rejected('waveform_trace_integrity')

    def test_rehashed_inventory_cannot_accept_replacement_trace(self):
        p = self.root / checks.WAVEFORM_TRACE
        # A valid gzip at the approved path still cannot replace its evidence.
        p.write_bytes(gzip.compress(gzip.decompress(p.read_bytes()) + b'\n#999999999\n'))
        self.rehash(checks.WAVEFORM_TRACE)
        result = self.rejected('waveform_trace_integrity')
        self.assertFalse(any('payload_hash' in x for x in result['errors']))

    def test_missing_registered_trace_rejected(self):
        (self.root / checks.WAVEFORM_TRACE).unlink()
        self.rejected('missing_payload')
        self.rejected('waveform_trace_integrity')

    def test_inventory_cannot_remove_required_trace(self):
        (self.root / checks.WAVEFORM_TRACE).unlink()
        p = self.root / self.inventory
        value = json.loads(p.read_text())
        value['files'] = [x for x in value['files'] if x['path'] != checks.WAVEFORM_TRACE]
        p.write_text(json.dumps(value))
        result = self.rejected('waveform_trace_integrity')
        self.assertFalse(any('payload_file_set' in x for x in result['errors']))

    def test_rehashed_inventory_cannot_accept_evidence_drift(self):
        relative = 'docs/v2/evidence/results/soc_cycles.csv'
        p = self.root / relative
        p.write_bytes(p.read_bytes() + b'\nEvidence corruption control.\n')
        self.rehash(relative)
        result = self.rejected('accepted_evidence_hash')
        self.assertTrue(any('protected_source_or_evidence_hash' in x for x in result['errors']))
        self.assertFalse(any('payload_hash' in x for x in result['errors']))

    def test_default_inventory_checks_current_layout(self):
        result = checks.validate(self.root)
        self.assertEqual(result['status'], 'PASS', result['errors'])
        self.assertEqual(checks.DEFAULT_INVENTORY, self.inventory)

    def test_broken_link_in_accepted_text(self):
        p = self.root / 'docs/v2/evidence/verification/formal_gap_review.txt'
        p.write_bytes(p.read_bytes() + b'\n[Injected missing evidence](absent-evidence.json)\n')
        result = self.rejected('broken_link')
        self.assertTrue(any(x.get('broken_link', {}).get('target') == 'absent-evidence.json'
                            for x in result['errors']))

    def test_missing_relocation_receipt(self):
        (self.root / 'docs/v2/evidence/results/host_formal.json').unlink()
        self.rejected('invalid_historical_relocation')

    def test_production_source_drift(self):
        p = self.root / 'rtl/v2/soc/flash_attn_soc.sv'
        p.write_bytes(p.read_bytes() + b'\n// Integrity negative control.\n')
        self.rejected('protected_source_or_evidence_hash')

    def test_rehashed_inventory_cannot_accept_source_drift(self):
        p = self.root / 'rtl/v2/soc/flash_attn_soc.sv'
        p.write_bytes(p.read_bytes() + b'\n// Integrity negative control.\n')
        manifest = self.root / self.inventory
        value = json.loads(manifest.read_text())
        row = next(x for x in value['files'] if x['path'] == str(p.relative_to(self.root)))
        row.update(sha256=hashlib.sha256(p.read_bytes()).hexdigest(), bytes=p.stat().st_size)
        manifest.write_text(json.dumps(value))
        self.rejected('protected_source_or_evidence_hash')

    def test_fixture_drift(self):
        p = self.root / 'data/exp_lut.hex'
        p.write_bytes(b'00\n' + p.read_bytes()[3:])
        self.rejected('protected_source_or_evidence_hash')

    def test_accepted_figure_drift(self):
        p = self.root / 'docs/v2/figures/historical_soc_architecture.svg'
        p.write_bytes(p.read_bytes() + b'\n<!-- Integrity negative control -->\n')
        self.rejected('figure_hash')

    def test_rehashed_inventory_cannot_accept_historical_figure_drift(self):
        p = self.root / 'docs/v2/figures/historical_soc_architecture.svg'
        p.write_bytes(p.read_bytes() + b'\n<!-- Integrity negative control -->\n')
        manifest = self.root / self.inventory
        value = json.loads(manifest.read_text())
        row = next(x for x in value['files'] if x['path'] == str(p.relative_to(self.root)))
        row.update(sha256=hashlib.sha256(p.read_bytes()).hexdigest(), bytes=p.stat().st_size)
        manifest.write_text(json.dumps(value))
        self.rejected('protected_source_or_evidence_hash')

    def test_current_architecture_figure_drift(self):
        for name in ('soc_architecture', 'memory_banking', 'shared_compute_timeline'):
            with self.subTest(figure=name):
                relative = f'docs/v2/figures/{name}.svg'
                p = self.root / relative
                original = p.read_bytes()
                try:
                    p.write_bytes(original + b'\n<!-- Integrity negative control -->\n')
                    result = self.rejected('payload_hash')
                    self.assertTrue(any(x.get('payload_hash') == relative
                                        for x in result['errors']), result['errors'])
                finally:
                    p.write_bytes(original)

    def test_undeclared_payload(self):
        (self.root / 'unreviewed-file.txt').write_text('Unreviewed addition\n')
        self.rejected('payload_file_set')

    def test_missing_source_map(self):
        (self.root / 'docs/v2/evidence/verification/source-map.json').unlink()
        self.rejected('validation_structure_error')

    def test_changed_historical_manifest(self):
        p = self.root / 'release/manifest-v1.json'
        p.write_bytes(p.read_bytes() + b'\n')
        self.rejected('historical_manifest_hash')

    def test_inconsistent_baseline_identity(self):
        p = self.root / self.inventory
        value = json.loads(p.read_text())
        value['base_commit'] = '0' * 40
        p.write_text(json.dumps(value))
        self.rejected('evidence_lock_schema')

    def test_invalid_manifest_structure(self):
        (self.root / self.inventory).write_text('[]\n')
        self.rejected('validation_structure_error')

    def test_unsafe_path_mapping(self):
        p = self.root / 'release/path-map-v1.json'
        value = json.loads(p.read_text())
        value['files'][0]['path'] = '../escaped'
        p.write_text(json.dumps(value))
        self.rejected('invalid_or_duplicate_origin')

    def test_functional_source_cannot_be_archived(self):
        p = self.root / 'release/layout-v2.json'
        value = json.loads(p.read_text())
        value['archived_preparation'].append(dict(
            path='rtl/v2/m6b3/flash_attn_soc_m6b3.sv', sha256='0' * 64))
        p.write_text(json.dumps(value))
        self.rejected('archive_policy')

    def test_arithmetic_patch_cannot_be_disguised_as_path_relocation(self):
        p = self.root / 'release/layout-v2.json'
        value = json.loads(p.read_text())
        row = value['path_only_derivatives'][0]
        row['replacements'] = [{'from':'old_value + data_in', 'to':'data_in', 'count':1}]
        p.write_text(json.dumps(value))
        self.rejected('path_patch_policy')

    def rehash(self, relative):
        p = self.root / relative
        manifest = self.root / self.inventory
        value = json.loads(manifest.read_text())
        row = next(x for x in value['files'] if x['path'] == relative)
        row.update(sha256=hashlib.sha256(p.read_bytes()).hexdigest(), bytes=p.stat().st_size)
        manifest.write_text(json.dumps(value))

    def comment_records(self):
        return json.loads((self.root / 'release/layout-v2.json').read_text())['comment_only_derivatives']

    def test_exact_comment_reconstruction_and_unchanged_lines(self):
        records = self.comment_records()
        self.assertEqual(len(records), 4)
        self.assertEqual(sum(len(x['replacements']) for x in records), 9)
        for row in records:
            with self.subTest(path=row['to']):
                data = (self.root / row['to']).read_bytes()
                original = checks.reverse_comment_spans(data, row)
                self.assertEqual(hashlib.sha256(data).hexdigest(), row['current_sha256'])
                self.assertEqual(hashlib.sha256(original).hexdigest(), row['original_sha256'])
                current_lines, original_lines = data.splitlines(keepends=True), original.splitlines(keepends=True)
                self.assertEqual(len(current_lines), len(original_lines))
                authorized = {i for op in row['replacements']
                              for i in range(op['line'] - 1, op['line'] - 1 + len(op['to'].splitlines()))}
                for i, (before, after) in enumerate(zip(original_lines, current_lines)):
                    if i not in authorized:
                        self.assertEqual(before, after, (row['to'], i + 1))
        result = checks.validate(self.root)
        self.assertEqual(result['status'], 'PASS', result['errors'])
        self.assertEqual(result['comment_only_derivatives'], 4)

    def test_registered_source_corruption_after_inventory_rehash(self):
        for row in self.comment_records():
            with self.subTest(path=row['to']):
                p = self.root / row['to']
                original = p.read_bytes()
                try:
                    p.write_bytes(original + b'// Unregistered comment.\n')
                    self.rehash(row['to'])
                    self.rejected('comment_derivative_contract')
                finally:
                    p.write_bytes(original)
                    self.rehash(row['to'])

    def test_comment_contract_cannot_expand_through_inventory_rehash(self):
        p = self.root / 'release/layout-v2.json'
        original = p.read_bytes()
        for mutation in ('extra_file', 'extra_span', 'code', 'directive', 'assertion',
                         'forged_current_hash', 'forged_original_hash', 'wrong_base', 'duplicate_file'):
            with self.subTest(mutation=mutation):
                value = json.loads(original)
                records = value['comment_only_derivatives']
                if mutation == 'extra_file':
                    forged = dict(records[0]); forged['to'] = 'rtl/v2/soc/flash_attn_soc.sv'; records.append(forged)
                elif mutation == 'extra_span':
                    records[0]['replacements'].append(dict(line=2, count=1, **{'from':'// old\n', 'to':'// new\n'}))
                elif mutation in ('code', 'directive', 'assertion'):
                    records[0]['replacements'][0]['to'] = {
                        'code':'assign ready = 1;\n',
                        'directive':'// verilator lint_off WIDTH\n',
                        'assertion':'assert (ready);\n'}[mutation]
                elif mutation == 'forged_current_hash': records[0]['current_sha256'] = '0' * 64
                elif mutation == 'forged_original_hash': records[0]['original_sha256'] = '0' * 64
                elif mutation == 'wrong_base': records[0]['base_commit'] = '0' * 40
                else: records.append(dict(records[0]))
                p.write_text(json.dumps(value))
                self.rehash('release/layout-v2.json')
                self.rejected('comment_derivative_contract')
        p.write_bytes(original)

    def test_missing_comment_contract_cannot_bypass_historical_hashes(self):
        p = self.root / 'release/layout-v2.json'
        value = json.loads(p.read_text())
        del value['comment_only_derivatives']
        p.write_text(json.dumps(value))
        self.rehash('release/layout-v2.json')
        self.rejected('protected_source_or_evidence_hash')

    def test_executable_and_directive_corruption_in_registered_source(self):
        relative = 'rtl/v2/compute/tile_controller_decode.sv'
        p = self.root / relative; original = p.read_bytes()
        variants = [original.replace(b'parameter int TILE_SIZE = 16', b'parameter int TILE_SIZE = 8', 1),
                    original.replace(b'input  logic clk,', b'input  logic clk_changed,', 1),
                    original.replace(b'if (1\'b0 && next_tile_valid', b'if (1\'b1 && next_tile_valid', 1),
                    original.replace(b'`timescale 1ns/1ps', b'`timescale 10ns/1ps', 1),
                    original.replace(b'/* verilator lint_off UNUSEDPARAM */', b'/* verilator lint_off WIDTH */', 1),
                    original + b'// synthesis translate_off\n',
                    original + b'assert (1);\n']
        for index, data in enumerate(variants):
            with self.subTest(mutation=index):
                self.assertNotEqual(data, original)
                p.write_bytes(data); self.rehash(relative)
                self.rejected('comment_derivative_contract')

    def test_comment_span_ambiguity_and_wrong_position(self):
        row = self.comment_records()[0]
        data = (self.root / row['to']).read_bytes()
        with self.assertRaisesRegex(ValueError, 'ambiguity'):
            checks.reverse_comment_spans(data + row['replacements'][0]['to'].encode(), row)
        forged = json.loads(json.dumps(row)); forged['replacements'][0]['line'] += 1
        with self.assertRaisesRegex(ValueError, 'position'):
            checks.reverse_comment_spans(data, forged)

    def test_span_cannot_contain_code_or_tool_directives(self):
        for text in ('assign ready = 1;\n', '// synthesis translate_off\n',
                     '// verilator lint_off WIDTH\n', '// synopsys full_case\n',
                     '// pragma coverage off\n', 'assert (ready);\n', '`define FLAG 1\n'):
            with self.subTest(span=text):
                row = dict(to='test.sv', replacements=[dict(line=1, count=1, **{'from':'// old\n', 'to':text})])
                with self.assertRaisesRegex(ValueError, 'ordinary comment'):
                    checks.reverse_comment_spans(text.encode(), row)

    def test_comment_span_geometry_and_overlap(self):
        for changes in ({'line':0}, {'count':2}, {'from':'// old\n// extra\n'},
                        {'to':'// new'}, {'to':'// new\r\n'}):
            with self.subTest(changes=changes):
                op = dict(line=1, count=1, **{'from':'// old\n', 'to':'// new\n'}); op.update(changes)
                with self.assertRaises(ValueError):
                    checks.reverse_comment_spans(op['to'].encode(), dict(to='test.sv', replacements=[op]))
        op = dict(line=1, count=1, **{'from':'// old\n', 'to':'// new\n'})
        with self.assertRaisesRegex(ValueError, 'geometry'):
            checks.reverse_comment_spans(b'// new\n', dict(to='test.sv', replacements=[op, op]))

    def test_git_free_export_cli_passes(self):
        self.assertFalse((self.root / '.git').exists())
        with tempfile.TemporaryDirectory(prefix='v2-export-report-') as out:
            output = pathlib.Path(out) / 'result.json'
            result = subprocess.run([sys.executable, '-B', str(self.root / 'tools/v2/validate_release.py'),
                                     '--output', str(output)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertEqual(json.loads(output.read_text())['comment_only_derivatives'], 4)

    def test_cli_exits_nonzero_on_failure(self):
        (self.root / 'rtl/v2/soc/soc.f').unlink()
        # Put the report outside the checked snapshot, avoiding an undeclared-file side effect.
        with tempfile.TemporaryDirectory(prefix='v2-cli-report-') as out:
            output = pathlib.Path(out) / 'result.json'
            result = subprocess.run([sys.executable, '-B', str(ROOT / 'tools/v2/validate_release.py'),
                                     '--snapshot', str(self.root), '--inventory', self.inventory, '--output', str(output)],
                                    capture_output=True, text=True)
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            self.assertEqual(json.loads(output.read_text())['status'], 'FAIL')


